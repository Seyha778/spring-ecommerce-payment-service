-- 3. ORDER SERVICE
-- ============================================================

-- Orders
CREATE TABLE IF NOT EXISTS ecommerce.orders (
                                                id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
    order_number VARCHAR(50) NOT NULL UNIQUE,
    customer_id VARCHAR(150) NOT NULL,
    customer_name VARCHAR(150),
    customer_email VARCHAR(150),
    subtotal NUMERIC(18,2) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(18,2) NOT NULL DEFAULT 0,
    shipping_fee NUMERIC(18,2) NOT NULL DEFAULT 0,
    tax_amount NUMERIC(18,2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(18,2) NOT NULL DEFAULT 0,
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    order_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    payment_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    payment_id VARCHAR(150),
    notes TEXT,
    created_on TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by varchar(255) NULL,
    modified_on TIMESTAMPTZ,
    modified_by varchar(255) null

    CONSTRAINT chk_order_amounts CHECK (
                                           subtotal >= 0 AND
                                           discount_amount >= 0 AND
                                           shipping_fee >= 0 AND
                                           tax_amount >= 0 AND
                                           total_amount >= 0
                                       )
    );

-- Order items
CREATE TABLE IF NOT EXISTS ecommerce.order_items (
                                                     id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
    order_id VARCHAR(150) NOT NULL,
    product_id VARCHAR(150) NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    product_sku VARCHAR(100),
    product_image TEXT,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(18,2) NOT NULL,
    discount_amount NUMERIC(18,2) NOT NULL DEFAULT 0,
    total_price NUMERIC(18,2) NOT NULL,
    created_on TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by varchar(255) NULL,

    CONSTRAINT chk_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_order_item_price CHECK (
                                              unit_price >= 0 AND
                                              discount_amount >= 0 AND
                                              total_price >= 0
                                          )
    );

-- Order status history
CREATE TABLE IF NOT EXISTS ecommerce.order_status_history (
                                                              id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
    order_id VARCHAR(150) NOT NULL,
    old_status VARCHAR(30),
    new_status VARCHAR(30) NOT NULL,
    changed_by VARCHAR(150),
    change_reason TEXT,
    created_on TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by varchar(255) NULL
    );

-- Order addresses
CREATE TABLE IF NOT EXISTS ecommerce.order_addresses (
                                                         id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
    order_id VARCHAR(150) NOT NULL,
    address_type VARCHAR(20) NOT NULL,
    recipient_name VARCHAR(150) NOT NULL,
    phone_number VARCHAR(30),
    address_line TEXT NOT NULL,
    city VARCHAR(100),
    province VARCHAR(100),
    postal_code VARCHAR(20),
    country VARCHAR(100),
    created_on TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by varchar(255) null,

    CONSTRAINT chk_order_address_type
    CHECK (address_type IN ('SHIPPING', 'BILLING'))
    );
